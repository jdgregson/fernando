test('content result clicks navigate new and existing chat frames to the exact event', () => {
    const dom = new JSDOM('<div id="conversationSearch"><input id="archiveSearch"><button id="clearConversationSearch"></button><div id="conversationSearchStatus"></div></div><div id="sessionList"><div class="session-item" data-session="chat:aaaaaaaa"><span class="session-name">Other</span></div></div><div id="browser"></div>', {url: 'https://fernando.test/', runScripts: 'outside-only'});
    const win = dom.window;
    const events = new Map();
    const emitted = [];
    win.socket = {on: (name, handler) => events.set(name, handler)};
    win.emitWithCsrf = (name, data) => emitted.push({name, data});
    win.FERNANDO_API_KEY = 'test-key';
    win.eval(fs.readFileSync(require('node:path').join(__dirname, '../src/static/js/chat.js'), 'utf8'));
    const browser = win.document.getElementById('browser');
    win.paneController = {open: key => win.mountChat({key, browser})};
    const input = win.document.getElementById('archiveSearch');
    input.value = '"my-test-1" -user';
    win.filterArchived();
    const response = {query: input.value, scope: 'active', request_id: emitted.at(-1).data.request_id, sessions: [{id: 'aaaaaaaa', snippet: 'my-test-1', match: 'Tool content', event_index: 42, source: 'tool:rawOutput', match_text: 'my-test-1'}]};
    events.get('acp_conversation_search_results')(response);
    win.document.querySelector('.conversation-search-preview').click();
    const frame = browser.querySelector('iframe');
    let params = new URLSearchParams(new URL(frame.src).hash.slice(1));
    assert.equal(params.get('search-event'), '42');
    assert.equal(params.get('search-source'), 'tool:rawOutput');
    const previousRequest = params.get('search-request');
    win.document.querySelector('.conversation-search-preview').click();
    assert.equal(browser.querySelector('iframe'), frame);
    params = new URLSearchParams(new URL(frame.src).hash.slice(1));
    assert.notEqual(params.get('search-request'), previousRequest);
    win.clearConversationSearch();
    dom.window.close();
});

test('active search scopes requests, rejects stale results, safely highlights snippets and clears', async () => {
    const dom = new JSDOM('<div id="conversationSearch"><input id="archiveSearch"><button id="clearConversationSearch"></button><div id="conversationSearchStatus"></div></div><div id="sessionList"><div class="session-item" data-session="chat:a"><span class="session-name">Camping</span></div><div class="session-item" data-session="chat:b"><span class="session-name">Other</span></div></div>', {runScripts: 'outside-only'});
    const win = dom.window;
    const events = new Map();
    const emitted = [];
    win.socket = {on: (name, handler) => events.set(name, handler)};
    win.emitWithCsrf = (name, data) => emitted.push({name, data});
    win.eval(fs.readFileSync(require('node:path').join(__dirname, '../src/static/js/chat.js'), 'utf8'));
    const input = win.document.getElementById('archiveSearch');
    input.value = 'tent';
    win.filterArchived();
    await new Promise(resolve => setTimeout(resolve, 350));
    assert.equal(emitted.at(-1).data.scope, 'active');
    const response = {...emitted.at(-1).data, sessions: [{id: 'a', snippet: '<img src=x onerror=alert(1)> tent', match: 'Related content'}]};
    events.get('acp_conversation_search_results')({...response, scope: 'archived'});
    assert.equal(win.document.querySelector('[data-session="chat:a"]').style.display, 'none');
    events.get('acp_conversation_search_results')(response);
    assert.equal(win.document.querySelector('.conversation-search-preview mark').textContent, 'tent');
    assert.equal(win.document.querySelector('img'), null);
    assert.equal(win.document.getElementById('clearConversationSearch').hidden, false);
    win.clearConversationSearch();
    events.get('acp_conversation_search_results')(response);
    assert.equal(win.document.querySelector('.conversation-search-preview'), null);
    assert.equal(win.document.getElementById('conversationSearchStatus').hidden, true);
    assert.equal(win.document.querySelector('[data-session="chat:b"]').style.display, '');
    input.value = '"Camping"';
    win.filterArchived();
    assert.equal(win.document.querySelector('[data-session="chat:a"]').style.display, '');
    assert.equal(win.document.querySelector('[data-session="chat:b"]').style.display, 'none');
    assert.match(win.document.getElementById('conversationSearchStatus').textContent, /1 exact matches/);
    win.clearConversationSearch();
    dom.window.close();
});

test('group menu inserts a scoped query and progressive replies accumulate without restarting', () => {
    const dom = new JSDOM('<div id="conversationSearch"><input id="archiveSearch"><button id="clearConversationSearch"></button><div id="conversationSearchStatus"></div></div><div id="sessionList">' + ['a5055f9f', 'bbbbbbbb'].map((id, i) => `<div class="group-wrapper" data-group-id="${id}"><span class="group-name">Group ${i}</span><span class="group-chevron"></span><div class="group-body"><div class="session-item" data-session="chat:${i}"><span class="session-name">Conversation ${i}</span></div></div></div>`).join('') + '</div>', {runScripts: 'outside-only'});
    const win = dom.window;
    const events = new Map();
    const emitted = [];
    win.socket = {on: (name, handler) => events.set(name, handler)};
    win.emitWithCsrf = (name, data) => emitted.push({name, data});
    win.eval(fs.readFileSync(require('node:path').join(__dirname, '../src/static/js/chat.js'), 'utf8'));
    const source = fs.readFileSync(require('node:path').join(__dirname, '../src/static/js/sessions.js'), 'utf8');
    win.eval(source.slice(source.indexOf('function showGroupContextMenu('), source.indexOf('function setupDropZone(')));
    win.dismissContextMenus = () => win.document.querySelectorAll('.group-context-menu').forEach(menu => menu.remove());
    win.trackContextMenu = () => {};
    const input = win.document.getElementById('archiveSearch');
    input.value = '"needle phrase"';
    win.showGroupContextMenu('a5055f9f', 10, 10, 1);
    [...win.document.querySelectorAll('.context-menu-item')].find(item => item.textContent === 'Search group').click();
    assert.equal(input.value, 'group:a5055f9f "needle phrase"');
    const requestId = emitted.at(-1).data.request_id;
    const response = {query: input.value, request_id: requestId, scope: 'active'};
    events.get('acp_conversation_search_results')({...response, sessions: [{id: '0', snippet: 'needle phrase', match: 'Tool content'}]});
    assert.equal(win.document.querySelector('[data-session="chat:0"]').style.display, '');
    assert.equal(win.document.querySelector('[data-group-id="bbbbbbbb"]').style.display, 'none');
    const preview = win.document.querySelector('.conversation-search-preview');
    events.get('acp_conversation_search_results')({...response, state: 'searching', completed: 1, total: 4});
    assert.equal(win.document.querySelector('.conversation-search-preview'), preview);
    assert.match(win.document.getElementById('conversationSearchStatus').textContent, /1\/4 searched/);
    events.get('acp_conversation_search_results')({...response, sessions: [{id: '1', snippet: 'needle phrase'}]});
    assert.equal(win.document.querySelector('[data-session="chat:0"]').style.display, '');
    assert.equal(win.document.querySelector('[data-session="chat:1"]').style.display, 'none');
    win.searchConversationGroup('bbbbbbbb');
    assert.equal(input.value, 'group:bbbbbbbb "needle phrase"');
    win.clearConversationSearch();
    assert.equal(emitted.at(-1).name, 'acp_cancel_conversation_search');
    dom.window.close();
});
